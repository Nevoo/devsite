/**
 * Bakes a land/sea bitmask out of Natural Earth 110m land polygons.
 *
 *   node scripts/build-land-mask.mjs
 *
 * Writes src/content/land-mask.ts: an equirectangular grid of one bit per cell,
 * base64'd. The globe generates its dots at runtime and asks this whether each
 * one landed on ground.
 *
 * Why a bitmask and not the polygons, a PNG, or a baked list of points:
 *
 *   - polygons at runtime means point-in-polygon against ~127 features for
 *     every dot, on the main thread, during the hero's entrance.
 *   - a PNG means an image decode plus a canvas readback, so the globe would
 *     have to render empty and then repopulate, and it drags a second async
 *     failure mode into a component that already has one.
 *   - baking the dot positions themselves fixes the density at build time, so
 *     tuning the look would mean regenerating an asset.
 *
 * A bitmask is an O(1) lookup, it is synchronous, it arrives as part of the
 * module graph rather than as a fetch, and the dot count stays a number in
 * Globe.tsx that anyone can change.
 *
 * 1024x512 is 0.35 degrees per cell. A globe drawn 600px across resolves about
 * 0.6 degrees per pixel, so this is already finer than the screen. Source data
 * is Natural Earth, public domain: https://www.naturalearthdata.com/about/terms-of-use/
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const SRC = process.argv[2]
if (!SRC) {
  console.error('usage: node scripts/build-land-mask.mjs <ne_110m_land.geojson>')
  process.exit(1)
}

const W = 1024
const H = 512

const geo = JSON.parse(readFileSync(SRC, 'utf8'))

/** every ring in the file, flattened, each with its bounding box for prefiltering */
const rings = []
for (const feature of geo.features) {
  const { type, coordinates } = feature.geometry
  const polygons = type === 'Polygon' ? [coordinates] : coordinates
  for (const polygon of polygons) {
    // [0] is the outer ring, the rest are holes. Holes are lakes at this scale
    // and there are almost none in the 110m land set, so both are treated the
    // same and an odd crossing count decides — which handles holes correctly
    // anyway under the even-odd rule.
    for (const ring of polygon) {
      let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity
      for (const [x, y] of ring) {
        if (x < minX) minX = x
        if (x > maxX) maxX = x
        if (y < minY) minY = y
        if (y > maxY) maxY = y
      }
      rings.push({ ring, minX, maxX, minY, maxY })
    }
  }
}

/** even-odd crossing test */
function inRing(ring, x, y) {
  let inside = false
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i]
    const [xj, yj] = ring[j]
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside
  }
  return inside
}

const bytes = new Uint8Array((W * H) / 8)
let land = 0

for (let row = 0; row < H; row++) {
  // cell centres, so a cell represents the area around its sample rather than
  // its top-left corner
  const lat = 90 - ((row + 0.5) / H) * 180
  const candidates = rings.filter((r) => lat >= r.minY && lat <= r.maxY)
  for (let col = 0; col < W; col++) {
    const lng = -180 + ((col + 0.5) / W) * 360
    let hit = false
    for (const c of candidates) {
      if (lng < c.minX || lng > c.maxX) continue
      if (inRing(c.ring, lng, lat)) hit = !hit
    }
    if (hit) {
      const bit = row * W + col
      bytes[bit >> 3] |= 128 >> (bit & 7)
      land++
    }
  }
}

const b64 = Buffer.from(bytes).toString('base64')
const pct = ((land / (W * H)) * 100).toFixed(1)

writeFileSync(
  join(ROOT, 'src/content/land-mask.ts'),
  `/* GENERATED by scripts/build-land-mask.mjs — do not edit by hand.
   Natural Earth 110m land, public domain. ${W}x${H} equirectangular, one bit
   per cell, row-major from 90N/180W. ${pct}% of cells are land. */

export const MASK_W = ${W}
export const MASK_H = ${H}

const PACKED =
  '${b64}'

/** unpacked once at module load; ${(bytes.length / 1024).toFixed(0)}KB of bits */
const bits = Uint8Array.from(atob(PACKED), (c) => c.charCodeAt(0))

/** true if [lat, lng] in degrees falls on land */
export function isLand(lat: number, lng: number) {
  const row = Math.min(MASK_H - 1, Math.max(0, Math.floor(((90 - lat) / 180) * MASK_H)))
  const col = Math.min(MASK_W - 1, Math.max(0, Math.floor(((lng + 180) / 360) * MASK_W)))
  const bit = row * MASK_W + col
  return (bits[bit >> 3] & (128 >> (bit & 7))) !== 0
}
`
)

console.log(`wrote src/content/land-mask.ts — ${W}x${H}, ${pct}% land, ${(b64.length / 1024).toFixed(1)}KB base64`)
